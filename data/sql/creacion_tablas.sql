PRAGMA foreign_keys = ON;

-- =========================
-- DROP TABLAS
-- =========================

DROP TABLE IF EXISTS REGISTRO;
DROP TABLE IF EXISTS INTERVALO;
DROP TABLE IF EXISTS FRECUENCIA_HABITO;
DROP TABLE IF EXISTS HABITO;
DROP TABLE IF EXISTS USUARIO;
DROP TABLE IF EXISTS CODIGO;
DROP TABLE IF EXISTS TIPO;

-- =========================
-- TABLAS CATALOGO
-- =========================

CREATE TABLE TIPO (
    ID_TIPO INTEGER PRIMARY KEY AUTOINCREMENT,
    NOMBRE TEXT NOT NULL UNIQUE
);

CREATE TABLE CODIGO (
    ID_CODIGO INTEGER PRIMARY KEY AUTOINCREMENT,
    ID_TIPO INTEGER NOT NULL,
    VALOR TEXT NOT NULL,
    DESPLIEGUE TEXT NOT NULL,

    -- FK
    FOREIGN KEY (ID_TIPO) REFERENCES TIPO(ID_TIPO),

    -- Evita duplicados dentro del mismo tipo
    UNIQUE (ID_TIPO, VALOR)
);

-- =========================
-- TABLAS PRINCIPALES
-- =========================

CREATE TABLE USUARIO (
    ID_USUARIO INTEGER PRIMARY KEY AUTOINCREMENT,
    NOMBRE_USUARIO TEXT NOT NULL,
    EMAIL TEXT NOT NULL UNIQUE,
    PASSWORD TEXT NOT NULL,
    ESTADO_USUARIO INTEGER NOT NULL,
    CHECK (ESTADO_USUARIO IN (0, 1))
);

CREATE TABLE HABITO (
    ID_HABITO INTEGER PRIMARY KEY AUTOINCREMENT,
    NOMBRE_HABITO TEXT NOT NULL,
    DESCRIPCION TEXT,
    ID_CODIGO_TIPO_HABITO INTEGER NOT NULL,
    ESTADO_HABITO INTEGER NOT NULL,
    HORA_INICIO TEXT,
    DURACION_OBJETIVO INTEGER,
    ID_USUARIO INTEGER NOT NULL,

    FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO) ON DELETE CASCADE,
	FOREIGN KEY (ID_CODIGO_TIPO_HABITO) REFERENCES CODIGO(ID_CODIGO),

    CHECK (ESTADO_HABITO IN (0, 1)),
    CHECK (DURACION_OBJETIVO IS NULL OR DURACION_OBJETIVO >= 0)
);

CREATE TABLE FRECUENCIA_HABITO (
    ID_FRECUENCIA_HABITO INTEGER PRIMARY KEY AUTOINCREMENT,
    ID_HABITO INTEGER NOT NULL,
    ID_CODIGO_TIPO_DIA_SEMANA INTEGER NOT NULL,

    FOREIGN KEY (ID_HABITO) REFERENCES HABITO(ID_HABITO) ON DELETE CASCADE,
	FOREIGN KEY (ID_CODIGO_TIPO_DIA_SEMANA) REFERENCES CODIGO(ID_CODIGO),
    -- Evita repetir el mismo día para un hábito
    UNIQUE (ID_HABITO, ID_CODIGO_TIPO_DIA_SEMANA)
);

CREATE TABLE INTERVALO (
    ID_INTERVALO INTEGER PRIMARY KEY AUTOINCREMENT,
    ID_HABITO INTEGER NOT NULL,
    INTERVALO_MINUTOS INTEGER NOT NULL,

    FOREIGN KEY (ID_HABITO) REFERENCES HABITO(ID_HABITO) ON DELETE CASCADE,

    CHECK (INTERVALO_MINUTOS > 0)
);

CREATE TABLE REGISTRO (
    ID_REGISTRO INTEGER PRIMARY KEY AUTOINCREMENT,
    ID_HABITO INTEGER NOT NULL,
    FECHA TEXT NOT NULL,
    ID_CODIGO_TIPO_ESTADO INTEGER NOT NULL,
    HORA_INICIO_REAL TEXT,
    DURACION_REAL INTEGER,

    FOREIGN KEY (ID_HABITO) REFERENCES HABITO(ID_HABITO) ON DELETE CASCADE,
	FOREIGN KEY (ID_CODIGO_TIPO_ESTADO) REFERENCES CODIGO(ID_CODIGO),
    CHECK (DURACION_REAL IS NULL OR DURACION_REAL >= 0)
);